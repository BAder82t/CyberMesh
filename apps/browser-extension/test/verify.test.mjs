test('older sequence is rejected as a rollback', async () => {
  const state = { sequence: 7, digest: expected.valid_digest };
  // The older release is itself valid without state.
  const older = await verifyRelease(fixtureBytes('release-older-sequence.json'), root, NOW);
  assert.equal(older.release.sequence, 6);
  await rejectsWith(verifyRelease(fixtureBytes('release-older-sequence.json'), root, NOW, state), 'rollback');
});

test('same sequence with a different digest is equivocation', async () => {
  const state = { sequence: 7, digest: `sha256:${'0'.repeat(64)}` };
  await rejectsWith(verifyRelease(fixtureBytes('release-valid.json'), root, NOW, state), 'equivocation');
  // A genuinely different, correctly signed release claiming sequence 7.
  const r = validReleaseObject();
  r.generator = 'cybermesh-intelligence/other';
  const other = signedRelease(r);
  await rejectsWith(verifyRelease(other, root, NOW, { sequence: 7, digest: expected.valid_digest }), 'equivocation');
});

test('the same release is accepted again with matching state', async () => {
  const v = await verifyRelease(fixtureBytes('release-valid.json'), root, NOW, { sequence: 7, digest: expected.valid_digest });
  assert.equal(v.digest, expected.valid_digest);
});

test('lookups: block, subdomain of block, warn, unlisted', async () => {
  const v = await verifyRelease(fixtureBytes('release-valid.json'), root, NOW);
  const index = buildIndex(v.release.entries);
  assert.equal(lookupHost(index, expected.block)?.action, 'block');
  assert.equal(lookupHost(index, expected.block)?.indicator, expected.block);
  assert.equal(lookupHost(index, expected.subdomain_of_block)?.action, 'block');
  assert.equal(lookupHost(index, expected.subdomain_of_block)?.indicator, expected.block);
  assert.equal(lookupHost(index, expected.warn)?.action, 'warn');
  assert.equal(lookupHost(index, expected.unlisted), null);
  assert.equal(lookupHost(index, 'phish.localhost'), null);
});

