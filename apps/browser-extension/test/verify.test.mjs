test('signatures from unknown keys and malformed signature entries are ignored', async () => {
  const env = JSON.parse(signedRelease(validReleaseObject()));
  const rogue = JSON.parse(signedRelease(validReleaseObject(), [testKey('attacker')]));
  env.signatures = [
    { keyid: 'not-hex', sig: 'AAAA' },
    rogue.signatures[0],
    { keyid: ORG_C.keyId, sig: '!!!' },
    { keyid: ORG_C.keyId.toUpperCase(), sig: env.signatures[0].sig },
    { keyid: ORG_A.keyId, sig: encodeBase64(new Uint8Array(63)) },
    ...env.signatures,
  ];
  const v = await verifyRelease(JSON.stringify(env), root, NOW);
  assert.deepEqual(v.operators, ['org-a', 'org-b']);
  assert.deepEqual(v.signers, [ORG_A.keyId, ORG_B.keyId]);
});

test('an invalid signature for a key does not prevent a later valid one from counting', async () => {
  const env = JSON.parse(signedRelease(validReleaseObject()));
  const bad = { keyid: ORG_A.keyId, sig: encodeBase64(new Uint8Array(64)) };
  env.signatures = [bad, ...env.signatures];
  const v = await verifyRelease(JSON.stringify(env), root, NOW);
  assert.deepEqual(v.operators, ['org-a', 'org-b']);
});

test('non-canonical signature scalar (S + L) is not counted', async () => {
  const env = JSON.parse(signedRelease(validReleaseObject()));
  const L = (1n << 252n) + 27742317777372353535851937790883648493n;
  const sig = Buffer.from(env.signatures[0].sig, 'base64');
  let s = 0n;
  for (let i = 63; i >= 32; i--) s = (s << 8n) | BigInt(sig[i]);
  s += L;
  for (let i = 32; i < 64; i++) {
    sig[i] = Number(s & 0xffn);
    s >>= 8n;
  }
  env.signatures[0].sig = sig.toString('base64');
  await rejectsWith(verifyRelease(JSON.stringify(env), root, NOW), 'threshold');
});

