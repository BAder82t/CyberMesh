test('anti-rollback: sequence jump limit and previous-release link', async () => {
  const state = { sequence: 7, digest: expected.valid_digest };
  const next = validReleaseObject();
  next.sequence = 8;
  next.previous = { sequence: 7, digest: expected.valid_digest };
  const v = await verifyRelease(signedRelease(next), root, NOW, state);
  assert.equal(v.release.sequence, 8);

  const forked = validReleaseObject();
  forked.sequence = 8;
  forked.previous = { sequence: 7, digest: `sha256:${'1'.repeat(64)}` };
  await rejectsWith(verifyRelease(signedRelease(forked), root, NOW, state), 'invalid');

  const unlinked = validReleaseObject();
  unlinked.sequence = 8;
  await verifyRelease(signedRelease(unlinked), root, NOW, state);

  // The link is only checked for the immediate successor.
  const later = validReleaseObject();
  later.sequence = 9;
  later.previous = { sequence: 8, digest: `sha256:${'2'.repeat(64)}` };
  await verifyRelease(signedRelease(later), root, NOW, state);

  const maxJump = validReleaseObject();
  maxJump.sequence = 7 + 1_000_000;
  await verifyRelease(signedRelease(maxJump), root, NOW, state);
  const tooFar = validReleaseObject();
  tooFar.sequence = 7 + 1_000_001;
  await rejectsWith(verifyRelease(signedRelease(tooFar), root, NOW, state), 'invalid');
});

