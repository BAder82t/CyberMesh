test('trust root parsing is strict', async () => {
  const tr = JSON.parse(fixtureText('trust-root.json'));
  const bad = [
    { ...tr, extra: 1 },
    { network_id: tr.network_id, signers: tr.signers },
    { ...tr, threshold: 256 },
    { ...tr, threshold: -1 },
    { ...tr, threshold: '2' },
    { ...tr, signers: [{ ...tr.signers[0], operator: 'Org-A' }] },
    { ...tr, signers: [{ ...tr.signers[0], operator: 'a' }] },
    { ...tr, signers: [{ ...tr.signers[0], public_key: tr.signers[0].public_key.toUpperCase() }] },
    { ...tr, signers: [{ ...tr.signers[0], public_key: '01'.padEnd(64, '0') }] }, // identity point (weak)
    { ...tr, signers: [{ ...tr.signers[0], role: 'x' }] },
  ];
  for (const b of bad) {
    await assert.rejects(parseTrustRoot(JSON.stringify(b)), (e) => e instanceof ReleaseError && e.code === 'trust-root');
  }
  await assert.rejects(parseTrustRoot('{"network_id":"a","network_id":"b","threshold":1,"signers":[]}'), ReleaseError);
  await assert.rejects(parseTrustRoot('{"network_id":"a","threshold":2.0,"signers":[]}'), ReleaseError);
  await assert.rejects(verifyRelease(fixtureBytes('release-valid.json'), JSON.parse(fixtureText('trust-root.json')), NOW), ReleaseError);
});
